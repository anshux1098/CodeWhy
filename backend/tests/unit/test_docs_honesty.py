"""Documentation and generated artifacts must be traceable and true.

A review file that nobody can regenerate, containing quotes that appear in no
cached source, is worse than no file at all.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

import pytest

REVIEW = Path("review")


def review_files() -> list[Path]:
    return sorted(REVIEW.glob("*.md"))


def test_the_fabricated_decisions_sample_is_gone() -> None:
    sample = REVIEW / "decisions_sample.md"
    assert not sample.exists(), (
        "decisions_sample.md was not produced by scripts/extract.py and its quotes "
        "appear in no cached source; it must not be committed"
    )


def test_the_extractor_no_longer_writes_it_by_default() -> None:
    source = Path("scripts/extract.py").read_text(encoding="utf-8")
    assert "--sample-review-file" in source, (
        "the sample file must be opt-in, so a fabricated one cannot be regenerated "
        "into the tree by a default run"
    )


@pytest.mark.parametrize("path", review_files(), ids=lambda p: p.name)
def test_every_review_file_names_the_command_that_produced_it(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    assert "Generated by" in text, f"{path.name} does not say what produced it"
    assert re.search(r"`?\.(?:venv|Scripts)[^\s`]*python\.exe scripts\\[a-z_]+\.py|`?scripts/[a-z_]+\.py",
                     text), f"{path.name} does not name the exact command"


@pytest.mark.parametrize("path", review_files(), ids=lambda p: p.name)
def test_no_review_file_claims_data_the_cache_does_not_hold(path: Path) -> None:
    """A review file may not cite a pull request the ingest cache never stored."""
    if not Path("data/ingest.sqlite3").exists():
        pytest.skip("no ingest cache on this machine")
    text = path.read_text(encoding="utf-8")
    numbers = {int(n) for n in re.findall(r"/pull/(\d+)", text)}
    if not numbers:
        pytest.skip("no pull request references in this file")

    import sqlite3

    connection = sqlite3.connect("file:data/ingest.sqlite3?mode=ro", uri=True)
    try:
        cached = {str(row[0]) for row in connection.execute(
            "SELECT json FROM raw_objects WHERE kind = 'pr'"
        )}
    finally:
        connection.close()
    present = set()
    for blob in cached:
        present.update(re.findall(r"/pull/(\d+)", blob))
    missing = numbers - present
    if path.name in {"repo_sampling_alembic.md", "history_probe_alembic.md",
                     "target_probe_alembic.md"}:
        pytest.skip("probe of a repository that has not been ingested")
    assert not missing, f"{path.name} cites pull requests absent from the cache: {sorted(missing)[:5]}"


def test_target_probe_has_rows_again() -> None:
    """The commit reduced it to header-only tables."""
    path = REVIEW / "target_probe.md"
    if not path.exists():
        pytest.skip("probe not present")
    body = path.read_text(encoding="utf-8")
    table_rows = [l for l in body.splitlines() if l.startswith("| ") and "---" not in l]
    assert len(table_rows) > 6, "the probe should contain measured rows, not only headers"


