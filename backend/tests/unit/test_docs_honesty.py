def test_readme_states_the_real_test_count() -> None:
    import re

    readme = Path("README.md").read_text(encoding="utf-8")
    result = subprocess.run(
        [".\\.venv\\Scripts\\python.exe", "-m", "pytest", "backend/tests", "-p", "no:warnings",
         "--collect-only", "-q"],
        capture_output=True, text=True,
    )
    total = 0
    for line in result.stdout.splitlines():
        m = re.search(r"(\d+) tests? collected", line)
        if m:
            total = int(m.group(1))
    if not total:
        pytest.skip("could not count tests")
    assert str(total) in readme, f"the README must state the real collected total ({total})"


