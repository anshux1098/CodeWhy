from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Optional, Sequence

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.config import Settings, SettingsError
from app.services.ingest.github_client import GitHubError, GitHubGraphQLClient
from app.services.ingest.sampling import (
    RepoSample,
    failure_row,
    render_definitions,
    render_table,
    summarise,
)

DEFAULT_CANDIDATES = (
    "urllib3/urllib3",
    "psf/requests",
    "encode/httpx",
    "pallets/flask",
    "celery/celery",
)
SAMPLE_SIZE = 50
OUTPUT_PATH = ROOT / "review" / "repo_sampling.md"

SAMPLING_QUERY = """
query SamplePullRequests($owner: String!, $name: String!, $count: Int!) {
  rateLimit {
    cost
    limit
    remaining
    resetAt
  }
  repository(owner: $owner, name: $name) {
    nameWithOwner
    primaryLanguage {
      name
    }
    defaultBranchRef {
      name
    }
    diskUsage
    pullRequests(
      states: MERGED
      first: $count
      orderBy: {field: CREATED_AT, direction: DESC}
    ) {
      totalCount
      nodes {
        number
        title
        body
        mergedAt
        author {
          login
        }
        reviews(first: 1) {
          totalCount
        }
        closingIssuesReferences(first: 10) {
          nodes {
            number
            title
            labels(first: 20) {
              nodes {
                name
              }
            }
          }
        }
        files(first: 100) {
          totalCount
          nodes {
            path
          }
        }
      }
    }
  }
}
""".strip()


def parse_candidate(candidate: str) -> Optional[tuple[str, str]]:
    parts = candidate.strip().strip("/").split("/")
    if len(parts) != 2 or not all(parts):
        return None
    return parts[0], parts[1]


def collect(
    client: GitHubGraphQLClient,
    candidates: Sequence[str],
    sample_size: int,
) -> tuple[list[RepoSample], list[str]]:
    rows: list[RepoSample] = []
    notes: list[str] = []
    for candidate in candidates:
        snapshot = client.rate_limit
        if snapshot is not None and snapshot.is_low():
            rows.append(failure_row(candidate, "skipped: rate limit low before this repo"))
            notes.append(f"{candidate}: skipped, rate limit was {snapshot.describe()}")
            continue
        parsed = parse_candidate(candidate)
        if parsed is None:
            rows.append(failure_row(candidate, "skipped: not in owner/name form"))
            notes.append(f"{candidate}: skipped, not in owner/name form")
            continue
        owner, name = parsed
        try:
            payload = client.query(SAMPLING_QUERY, {"owner": owner, "name": name, "count": sample_size})
        except GitHubError as exc:
            reason = str(exc).splitlines()[0][:120]
            rows.append(failure_row(candidate, f"failed: {reason}"))
            notes.append(f"{candidate}: failed, {reason}")
            continue
        row = summarise(candidate, payload)
        rows.append(row)
        if row.status != "ok":
            notes.append(f"{candidate}: {row.status}")
    return rows, notes


def build_report(rows: Sequence[RepoSample], notes: Sequence[str], cost: str, sample_size: int) -> str:
    parts = [
        "# Repository sampling",
        "",
        "Generated by `scripts/sample_repos.py`. Every number below was measured from the GitHub",
        "GraphQL API at the time the script ran. No value here is estimated or hand-written.",
        "",
        f"Sample: the {sample_size} most recently created merged pull requests per repository,",
        "as returned by one GraphQL query per repository. Nothing is cloned.",
        "",
        render_table(rows),
        "",
        "Counts are out of the sampled pull requests, not out of the repository's whole history.",
        "Read the sample window column before comparing rows.",
        "",
        "## Definitions",
        "",
        render_definitions(),
        "",
        "## GraphQL cost",
        "",
        f"- Total cost reported by the API across this run: {cost}",
        "",
        "## Failures and skips",
        "",
    ]
    if notes:
        parts.extend(f"- {note}" for note in notes)
    else:
        parts.append("- None. Every candidate returned a row.")
    parts.append("")
    parts.append("No ranking and no recommendation is produced here; the repository is chosen by hand.")
    parts.append("")
    return "\n".join(parts)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Sample candidate repositories to compare for Phase 1b.")
    parser.add_argument("candidates", nargs="*", help="owner/name repositories; defaults to the five candidates")
    parser.add_argument("--sample-size", type=int, default=SAMPLE_SIZE)
    parser.add_argument("--output", default=str(OUTPUT_PATH))
    parser.add_argument("--dry-run", action="store_true", help="validate configuration without calling the API")
    args = parser.parse_args(argv)

    candidates = tuple(args.candidates) or DEFAULT_CANDIDATES

    try:
        config = Settings()
        config.require_github()
    except SettingsError as exc:
        print(f"cannot sample: {exc}", file=sys.stderr)
        return 2

    if args.dry_run:
        print(f"configuration is valid. {len(candidates)} candidates, sample size {args.sample_size}.")
        return 0

    rows: list[RepoSample] = []
    notes: list[str] = []
    with GitHubGraphQLClient(config) as client:
        rows, notes = collect(client, candidates, args.sample_size)
        snapshot = client.rate_limit
    cost = snapshot.cost if snapshot is not None else "not reported"

    table = render_table(rows)
    print(table)
    print()
    print("Definitions")
    print(render_definitions())
    print()
    print(f"Total GraphQL cost of the last query: {cost}")
    if snapshot is not None:
        print(f"Rate limit after the run: {snapshot.describe()}")
    print()
    print("Failures and skips")
    if notes:
        for note in notes:
            print(f"- {note}")
    else:
        print("- None. Every candidate returned a row.")
    print()
    print("No ranking is produced; the repository is chosen by hand.")

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(build_report(rows, notes, cost, args.sample_size), encoding="utf-8")
    print(f"wrote {output}")
    return 0 if all(row.status == "ok" for row in rows) else 1


if __name__ == "__main__":
    raise SystemExit(main())